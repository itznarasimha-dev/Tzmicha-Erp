import type { Lead, LeadActivity, LeadStatus, Opportunity } from '../../types/marketing'
import { daysFromNow } from '../../utils/dates'

interface LeadSeed {
  id: string
  name: string
  company: string
  phone: string
  email: string
  location: string
  industry: string
  source: Lead['source']
  campaignId: string | null
  product: string
  assignedTo: string
  status: LeadStatus
  priority: Lead['priority']
  nextFollowUp: string | null
  notes: string
  createdAt: string
  lastContact: string
  lostReason?: string
  customerId?: string
  activities: Array<Omit<LeadActivity, 'id'>>
}

function makeLead(seed: LeadSeed, index: number): Lead {
  const converted = seed.status === 'Converted'
  const [city = '', state = ''] = seed.location.split(',').map((part) => part.trim())
  return {
    ...seed,
    converted,
    ...(converted && !seed.customerId
      ? { customerId: `CUST-2026-${String(index).padStart(3, '0')}` }
      : {}),
    city: city || undefined,
    state: state || undefined,
    country: seed.location ? 'India' : undefined,
    interests: {
      // Only fields that can be derived from the recorded seed record are filled.
      products: seed.product ? [seed.product] : [],
      features: [],
      likes: [],
      dislikes: [],
      requirements: [],
      questions: [],
      problems: [],
    },
    qualification: {
      notes: seed.notes,
      mainRequirement: seed.notes,
    },
    attribution: {
      firstContactDate: seed.createdAt,
      latestContactDate: seed.lastContact,
    },
    followUps: [],
    activities: seed.activities.map((activity, activityIndex) => ({
      ...activity,
      id: `${seed.id}-ACT-${activityIndex + 1}`,
    })),
  }
}

