const task = (
  id: string,
  title: string,
  assignedToId: string,
  assignedById: string,
  status: WorkspaceTask['status'],
  priority: WorkspaceTask['priority'],
  deadlineOffset: number,
  expectedResult: string,
  options: Partial<WorkspaceTask> = {},
): WorkspaceTask => ({
  id,
  title,
  description: options.description ?? 'Execute the assigned marketing activity and update the workspace with progress and evidence.',
  assignedToId,
  assignedToName: employeeName(assignedToId),
  assignedById,
  assignedByName: employeeName(assignedById),
  priority,
  status,
  deadline: dateOnlyFromNow(deadlineOffset),
  expectedResult,
  instructions: options.instructions ?? 'Follow the campaign brief, capture lead details and update progress before the deadline.',
  progress: options.progress ?? (status === 'Completed' ? 100 : status === 'Under Review' ? 95 : status === 'In Progress' ? 55 : 0),
  category: options.category ?? 'Campaign Execution',
  campaignId: options.campaignId,
  createdAt: options.createdAt ?? daysFromNow(-Math.abs(deadlineOffset) - 4),
  updatedAt: options.updatedAt ?? daysFromNow(-1),
  reviewNote: options.reviewNote,
  managerTask: options.managerTask ?? true,
})

