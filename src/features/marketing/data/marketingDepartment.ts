function expense(
  id: string,
  title: string,
  amount: number,
  category: string,
  sectorId: string,
  employeeId: string,
  status: MarketingExpense['status'],
  taskId: string,
  taskTitle: string,
  dateOffset: number,
  description: string,
  receiptName: string,
  note: string,
): MarketingExpense {
  const employee = MARKETING_EMPLOYEES.find((item) => item.id === employeeId)
  const createdAt = daysFromNow(-(Math.abs(dateOffset) + 1), 12, 0)
  const timeline: MarketingExpense['timeline'] = [
    {
      id: `${id}-T1`,
      at: createdAt,
      actorId: employeeId,
      actorName: employee?.name ?? 'Marketing executive',
      actorRole: 'Marketing Executive',
      action: 'Expense submitted',
      note: description,
      tone: 'info',
    },
  ]
  if (status !== 'Submitted') {
    timeline.push({
      id: `${id}-T2`,
      at: daysFromNow(-(Math.abs(dateOffset) - 1), 15, 0),
      actorId: leaderFor(sectorId) ?? MANAGER_ID,
      actorName: MARKETING_EMPLOYEES.find((item) => item.id === leaderFor(sectorId))?.name ?? 'Senior Executive',
      actorRole: 'Senior Marketing Executive',
      action: 'Senior review completed',
      note,
      tone: status === 'Rejected' || status === 'Changes Requested' ? 'warning' : 'success',
    })
  }
  if (status === 'Finance Review' || status === 'Approved' || status === 'Rejected') {
    timeline.push({
      id: `${id}-T3`,
      at: daysFromNow(-(Math.abs(dateOffset) - 2), 11, 0),
      actorId: MANAGER_ID,
      actorName: 'Meera Iyer',
      actorRole: 'Marketing Manager',
      action: status === 'Rejected' ? 'Rejected by manager' : 'Forwarded to Finance/Admin',
      note: status === 'Rejected' ? note : 'Business justification verified. Final financial authorization is outside Marketing.',
      tone: status === 'Rejected' ? 'danger' : 'info',
    })
  }
  if (status === 'Approved') {
    timeline.push({
      id: `${id}-T4`,
      at: daysFromNow(-(Math.abs(dateOffset) - 4), 10, 0),
      actorId: FINANCE_ID,
      actorName: 'Priya Sharma',
      actorRole: 'Finance / Admin',
      action: 'Finance/Admin approved',
      note: 'Final financial approval recorded in the existing Admin workflow.',
      tone: 'success',
    })
  }
  return {
    id,
    title,
    amount,
    category,
    expenseDate: dateOnlyFromNow(dateOffset),
    sectorId,
    employeeId,
    employeeName: employee?.name ?? 'Marketing executive',
    taskId,
    taskTitle,
    description,
    receiptName,
    status,
    comments: note,
    createdAt,
    updatedAt: daysFromNow(-1, 12, 0),
    timeline,
  }
}

