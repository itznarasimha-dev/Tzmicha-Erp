const leaderFor = (sectorId: string) =>
  MARKETING_SECTORS.find((sector) => sector.id === sectorId)?.leaderId ?? null

const juniorFor = (sectorId: string, index: number) => {
  const team = MARKETING_EMPLOYEES.filter(
    (employee) => employee.role === 'junior' && employee.sectorId === sectorId,
  )
  return team[index % Math.max(1, team.length)]?.id ?? null
}

function review(
  id: string,
  actorId: string,
  actorRole: string,
  action: string,
  fromStage: MarketingLead['stage'],
  toStage: MarketingLead['stage'],
  note: string,
  daysAgo: number,
) {
  const actor = MARKETING_EMPLOYEES.find((employee) => employee.id === actorId)
  return {
    id,
    at: daysFromNow(-daysAgo, 11, 15),
    actorId,
    actorName: actor?.name ?? 'Marketing team',
    actorRole,
    action,
    fromStage,
    toStage,
    note,
  }
}

