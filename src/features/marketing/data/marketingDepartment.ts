function salesUpdateNote(daysAgo: number): string {
  if (daysAgo > 20) return 'Commercial discussion completed; final outcome recorded by Sales.'
  if (daysAgo > 12) return 'Customer requested a revised commercial proposal; Sales is following up.'
  return 'Customer qualification call completed; requirements confirmed with the buying team.'
}

interface LeadSeedOptions {
  stage?: MarketingLead['stage']
  juniorIndex?: number
  campaignId?: string | null
  expectedValue?: number
  customerBudget?: number
  priority?: MarketingLead['priority']
  createdAtDays?: number
  followUps?: MarketingLead['followUps']
  reviews?: MarketingLead['reviews']
  handover?: SalesHandover | null
  salesOutcome?: MarketingLead['salesOutcome']
  rejectionReason?: string
  location?: string
  product?: string
  requirements?: string
  phone?: string
}

function lead(
  id: string,
  name: string,
  businessName: string,
  sectorId: string,
  source: string,
  options: LeadSeedOptions = {},
): MarketingLead {
  const seniorId = leaderFor(sectorId)
  const juniorId = juniorFor(sectorId, options.juniorIndex ?? 0)
  const createdById = juniorId ?? seniorId ?? MANAGER_ID
  const stage = options.stage ?? 'New Lead'
  return {
    id,
    name,
    phone: options.phone ?? `+91 98${String(30000000 + Number(id.slice(-3)) * 137).slice(0, 8)}`,
    whatsapp: options.phone ?? `+91 98${String(30000000 + Number(id.slice(-3)) * 137).slice(0, 8)}`,
    email: `${name.toLowerCase().replace(/[^a-z]+/g, '.')}@${businessName
      .toLowerCase()
      .replace(/[^a-z]+/g, '')}.demo`,
    businessName,
    address: options.location ?? 'Business district, India',
    location: options.location ?? 'Bengaluru',
    product: options.product ?? 'Totally ERP Growth Suite',
    requirements: options.requirements ?? 'Interested in a connected ERP rollout for sales and marketing teams.',
    source,
    campaignId: options.campaignId ?? null,
    expectedValue: options.expectedValue ?? 480000,
    customerBudget: options.customerBudget ?? options.expectedValue ?? 480000,
    priority: options.priority ?? 'Medium',
    sectorId,
    createdById,
    assignedSeniorId: seniorId,
    assignedJuniorId: juniorId,
    stage,
    rejectionReason: options.rejectionReason ?? '',
    createdAt: daysFromNow(-(options.createdAtDays ?? 4), 10, 20),
    updatedAt: daysFromNow(-1, 17, 0),
    followUps: options.followUps ?? [],
    reviews: options.reviews ?? [],
    handover: options.handover ?? null,
    salesOutcome: options.salesOutcome ?? null,
  }
}

const seededFollowUps = (
  leadId: string,
  employeeId: string,
  entries: Array<{
    mode: MarketingLead['followUps'][number]['mode']
    result: MarketingLead['followUps'][number]['result']
    notes: string
    daysAgo: number
    nextOffset?: number
  }>,
) =>
  entries.map((entry, index) => {
    const employee = MARKETING_EMPLOYEES.find((item) => item.id === employeeId)
    return {
      id: `LFU-${leadId}-${index + 1}`,
      at: daysFromNow(-entry.daysAgo, 11, 30),
      mode: entry.mode,
      employeeId,
      employeeName: employee?.name ?? 'Marketing executive',
      result: entry.result,
      notes: entry.notes,
      nextActionAt: entry.nextOffset === undefined ? null : dateOnlyFromNow(entry.nextOffset),
    }
  })

