function withSeedPlanHistory(plan: MarketingPlan): MarketingPlan {
  const creator = MARKETING_EMPLOYEES.find((employee) => employee.id === plan.createdById)
  const manager = MARKETING_EMPLOYEES.find((employee) => employee.id === MANAGER_ID)
  const history: MarketingPlan['history'] = [
    {
      id: `${plan.id}-H0`,
      at: plan.createdAt,
      actorId: plan.createdById,
      actorName: creator?.name ?? 'Marketing team',
      actorRole: creator?.role === 'manager' ? 'Marketing Manager' : 'Marketing Executive',
      action: 'Plan created',
      note: `${plan.title} was created for ${plan.type.toLowerCase()} planning.`,
      tone: 'info',
    },
  ]
  if (['Pending Manager Review', 'Pending Finance Approval', 'Active', 'Completed'].includes(plan.status)) {
    history.push({
      id: `${plan.id}-H1`,
      at: plan.updatedAt,
      actorId: plan.createdById,
      actorName: creator?.name ?? 'Marketing team',
      actorRole: creator?.role === 'manager' ? 'Marketing Manager' : 'Marketing Executive',
      action: 'Submitted to manager',
      note: 'Plan submitted for manager review. Finance review follows manager approval.',
      tone: 'neutral',
    })
  }
  if (['Pending Finance Approval', 'Active', 'Completed'].includes(plan.status)) {
    history.push({
      id: `${plan.id}-H2`,
      at: plan.updatedAt,
      actorId: MANAGER_ID,
      actorName: manager?.name ?? 'Marketing Manager',
      actorRole: 'Marketing Manager',
      action: 'Manager approved and forwarded to Finance',
      note: 'Budget and objective validated. Finance/Admin review requested.',
      tone: 'success',
    })
  }
  if (['Active', 'Completed'].includes(plan.status)) {
    history.push({
      id: `${plan.id}-H3`,
      at: plan.updatedAt,
      actorId: FINANCE_ID,
      actorName: 'Priya Sharma',
      actorRole: 'Finance / Admin',
      action: 'Finance approved — plan active',
      note: 'Financial approval recorded. The plan is now active.',
      tone: 'success',
    })
  }
  return {
    ...plan,
    submittedAt: plan.status === 'Draft' ? null : plan.updatedAt,
    managerReviewedAt: ['Pending Finance Approval', 'Active', 'Completed'].includes(plan.status) ? plan.updatedAt : null,
    managerReviewerName: ['Pending Finance Approval', 'Active', 'Completed'].includes(plan.status) ? manager?.name : undefined,
    managerRemarks: ['Pending Finance Approval', 'Active', 'Completed'].includes(plan.status) ? 'Validated for the approved monthly envelope.' : '',
    financeReviewedAt: ['Active', 'Completed'].includes(plan.status) ? plan.updatedAt : null,
    financeReviewerName: ['Active', 'Completed'].includes(plan.status) ? 'Priya Sharma' : undefined,
    financeRemarks: ['Active', 'Completed'].includes(plan.status) ? 'Finance/Admin approved the plan budget.' : '',
    history,
  }
}

